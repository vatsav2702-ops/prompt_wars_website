function parseTimeToMinutes(timeStr: string): number {
  if (!timeStr) return 840; // 02:00 PM default
  const clean = timeStr.trim().toUpperCase();
  const match = clean.match(/(\d{1,2}):(\d{2})\s*(AM|PM)?/);
  if (!match) return 840;
  let hours = parseInt(match[1], 10);
  const minutes = parseInt(match[2], 10);
  const period = match[3];
  if (period === 'PM' && hours < 12) hours += 12;
  if (period === 'AM' && hours === 12) hours = 0;
  return hours * 60 + minutes;
}

function parseSlotRange(slot: string): { start: number; end: number } {
  const parts = slot.split('-');
  if (parts.length >= 2) {
    return {
      start: parseTimeToMinutes(parts[0]),
      end: parseTimeToMinutes(parts[1]),
    };
  }
  const single = parseTimeToMinutes(slot);
  return { start: single, end: single + 60 };
}

/**
 * Strict Schedule Directive Evaluator
 * Enforces:
 * 1. STRICT SCHEDULE ADHERENCE: ONLY reference tasks explicitly on user's schedule
 * 2. TIMING & REMINDER ACCURACY: ON_TASK, TRANSITION, or FREE_TIME; completion checks for passed tasks
 * 3. STRICT JSON SCHEMA: schedule_evaluation, reminders_and_checkins, schedule_audit, location_and_task_automation
 */
function evaluateStrictScheduleDirective(
  currentTimeStr: string,
  plannedTasks: PlannedTask[],
  fatigueIndex: "Low" | "Moderate" | "High" | "Critical",
  todaySleepHours: number,
  locationContext: LocationTriggerContext,
  recommendedAction: string,
  autoGeneratedContent: string
): StrictLifeOSOutput {
  const curMins = parseTimeToMinutes(currentTimeStr);
  let currentStatus: "ON_TASK" | "TRANSITION" | "FREE_TIME" = "FREE_TIME";
  let activeOrUpcomingTask: string | null = null;
  let matchingTask: PlannedTask | null = null;

  // 1. Check if user is currently inside an active scheduled slot
  for (const task of plannedTasks) {
    const range = parseSlotRange(task.time_slot);
    if (curMins >= range.start && curMins < range.end) {
      currentStatus = "ON_TASK";
      activeOrUpcomingTask = task.task_name;
      matchingTask = task;
      break;
    }
  }

  // 2. If not on task, check if approaching a task within 30 minutes
  if (!matchingTask) {
    for (const task of plannedTasks) {
      const range = parseSlotRange(task.time_slot);
      if (curMins < range.start && range.start - curMins <= 30) {
        currentStatus = "TRANSITION";
        activeOrUpcomingTask = task.task_name;
        matchingTask = task;
        break;
      }
    }
  }

  // 3. If still free, find next upcoming task
  if (!matchingTask) {
    currentStatus = "FREE_TIME";
    let earliestUpcoming: { task: PlannedTask; diff: number } | null = null;
    for (const task of plannedTasks) {
      const range = parseSlotRange(task.time_slot);
      if (range.start > curMins) {
        const diff = range.start - curMins;
        if (!earliestUpcoming || diff < earliestUpcoming.diff) {
          earliestUpcoming = { task, diff };
        }
      }
    }
    activeOrUpcomingTask = earliestUpcoming ? earliestUpcoming.task.task_name : null;
  }

  const remindersAndCheckins: ReminderAndCheckinItem[] = [];

  // Directive 2: If a task deadline or end time has passed, ask for status verification
  for (const task of plannedTasks) {
    const range = parseSlotRange(task.time_slot);
    if (curMins >= range.end) {
      remindersAndCheckins.push({
        trigger_time: currentTimeStr,
        associated_task: task.task_name,
        reminder_type: "TASK_COMPLETION_CHECK",
        message: `Have you finished ${task.task_name}? Scheduled slot (${task.time_slot}) has concluded.`,
      });
    }
  }

  // Directive 2: If current time matches or closely approaches a scheduled task, issue reminder/check-in
  if (matchingTask) {
    if (currentStatus === "ON_TASK") {
      remindersAndCheckins.push({
        trigger_time: currentTimeStr,
        associated_task: matchingTask.task_name,
        reminder_type: "TASK_START",
        message: `Currently active scheduled task: "${matchingTask.task_name}". Maintain deep focus through ${matchingTask.time_slot.split('-')[1]?.trim() || 'conclusion'}.`,
      });
    } else if (currentStatus === "TRANSITION") {
      remindersAndCheckins.push({
        trigger_time: currentTimeStr,
        associated_task: matchingTask.task_name,
        reminder_type: "TASK_START",
        message: `Approaching scheduled task: "${matchingTask.task_name}" commences at ${matchingTask.time_slot.split('-')[0]?.trim() || currentTimeStr}. Clear workspace now.`,
      });
    }
  } else {
    // Directive 2: If current time falls outside any scheduled tasks, acknowledge free/unscheduled time
    remindersAndCheckins.push({
      trigger_time: currentTimeStr,
      associated_task: activeOrUpcomingTask || "Unscheduled Block",
      reminder_type: "WELLNESS_CHECK",
      message: `You are currently in free/unscheduled time (${currentTimeStr}). No active tasks on your schedule. Rehydrate and deload.`,
    });
  }

  // Operational flow: meal check
  remindersAndCheckins.push({
    trigger_time: currentTimeStr,
    associated_task: activeOrUpcomingTask || "Circadian Nutrition",
    reminder_type: "MEAL_CHECK",
    message: `Circadian nutrition check: Verify you have eaten your meal and hydrated prior to your next focused cognitive sprint.`,
  });

  // Operational flow: wellness query (sleep & fatigue relevant to those specific slots)
  remindersAndCheckins.push({
    trigger_time: currentTimeStr,
    associated_task: activeOrUpcomingTask || "Somatic Health",
    reminder_type: "WELLNESS_CHECK",
    message: `Wellness check: Baseline sleep logged at ${todaySleepHours}h with fatigue at ${fatigueIndex}. Monitor ocular strain and take 60s postural reset.`,
  });

  // Schedule audit with DO | DON'T | RESCHEDULE
  const scheduleAudit = plannedTasks.map((task) => {
    const isLate = task.time_slot.includes("PM") && (task.time_slot.includes("07:") || task.time_slot.includes("08:") || task.time_slot.includes("09:") || task.time_slot.includes("02:"));
    const isIntense = task.cognitive_load === "High" || task.cognitive_load === "Intense";
    const isRecovery = task.category === "recovery" || task.category === "fitness";

    if (fatigueIndex === "Critical" && isIntense && isLate) {
      return {
        time_slot: task.time_slot,
        task_name: task.task_name,
        verdict: "RESCHEDULE" as const,
        reasoning: `RESCHEDULE: High cognitive fatigue with only ${todaySleepHours}h sleep. Shift this intensive task to tomorrow's peak morning window.`,
      };
    }
    if (fatigueIndex === "Critical" && isIntense) {
      return {
        time_slot: task.time_slot,
        task_name: task.task_name,
        verdict: "DON'T" as const,
        reasoning: `DON'T overload depleted neurological reserves. High error vulnerability; substitute with light review.`,
      };
    }
    if (isRecovery) {
      return {
        time_slot: task.time_slot,
        task_name: task.task_name,
        verdict: "DO" as const,
        reasoning: `DO preserve scheduled physical/mental recovery to stabilize parasympathetic tone.`,
      };
    }
    return {
      time_slot: task.time_slot,
      task_name: task.task_name,
      verdict: "DO" as const,
      reasoning: `DO proceed. Aligns with current energy reserve and circadian parameters.`,
    };
  });

  return {
    schedule_evaluation: {
      active_schedule_count: plannedTasks.length,
      current_time: currentTimeStr,
      current_status: currentStatus,
      active_or_upcoming_task: activeOrUpcomingTask,
    },
    reminders_and_checkins: remindersAndCheckins,
    schedule_audit: scheduleAudit,
    location_and_task_automation: {
      detected_location: locationContext.detected_location,
      automated_action: recommendedAction,
      generated_content: autoGeneratedContent,
    },
  };
}

