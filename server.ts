// Fallback logic for Time-Triggered Check-In and Wellness Suggestion Agent
function computeFallbackCheckIn(
  mode: 'GENERATE_CHECKIN' | 'EVALUATE_RESPONSE',
  currentTime: string,
  schedule: any[] = [],
  telemetry: any = {},
  answers?: any
): any {
  const currentTask = schedule.find((s: any) => s.time_slot && s.time_slot.includes(currentTime.split(' ')[0])) || schedule[0];
  const taskTitle = currentTask ? currentTask.task_name : 'your scheduled core activity';

  const defaultQuestions = [
    `How many hours of sleep did you get last night, and do you feel cognitively rested?`,
    `Have you had a balanced meal and stayed hydrated over the last 3-4 hours?`,
    `Did you successfully complete or make headway on "${taskTitle}"?`,
    `On a scale of 1 to 10, what is your current mental energy, executive focus, and fatigue level?`,
    `Are you experiencing physical tension, neck stiffness, or eye strain right now?`
  ];

  let triggerReason = 'Mid-day circadian alertness audit and schedule transition checkpoint';
  if (currentTime.includes('AM')) {
    triggerReason = 'Morning neuro-baseline initialization and focus window checkpoint';
  } else if (currentTime.includes('06:') || currentTime.includes('07:') || currentTime.includes('08:') || currentTime.includes('09:')) {
    triggerReason = 'Evening cognitive wind-down and somatic deload assessment';
  }

  const suggestions: any[] = [];
  const sleepResp = (answers?.sleep_response || '').toLowerCase();
  const mealResp = (answers?.nutrition_response || '').toLowerCase();
  const hydraResp = (answers?.hydration_breaks_response || '').toLowerCase();
  const taskResp = (answers?.task_completion_response || '').toLowerCase();
  const fatigueScore = typeof answers?.fatigue_level_score === 'number' ? answers.fatigue_level_score : (telemetry?.today_cognitive_fatigue ?? 6);

  // 1. Nutrition / Hydration
  if (mealResp.includes('no') || mealResp.includes('skip') || mealResp.includes('hungry') || hydraResp.includes('thirsty') || hydraResp.includes('coffee')) {
    suggestions.push({
      category: 'Nutrition / Hydration',
      suggestion_title: 'Electrolyte & Slow-Burn Glycemic Rebalance',
      actionable_advice: 'Drink 400ml of mineralized water with a pinch of electrolytes, paired with complex carbs and protein (e.g. nuts, seeds, or yogurt) to prevent rapid glucose crashes.',
      priority_level: 'High'
    });
  } else {
    suggestions.push({
      category: 'Nutrition / Hydration',
      suggestion_title: 'Cellular Hydration Maintenance',
      actionable_advice: 'Maintain a 250ml hydration sip cadence every 60-90 minutes. Limit caffeine intake past 02:00 PM to protect tonight\'s deep restorative sleep.',
      priority_level: 'Medium'
    });
  }

  // 2. Energy Management
  if (fatigueScore >= 7 || sleepResp.includes('tired') || sleepResp.includes('3') || sleepResp.includes('4') || sleepResp.includes('little')) {
    suggestions.push({
      category: 'Energy Management',
      suggestion_title: '15-Minute Non-Sleep Deep Rest (NSDR / Reset)',
      actionable_advice: 'Lie flat or recline with eyes closed for 12-15 minutes utilizing physiological sighs (two quick inhales, slow exhale) to recalibrate autonomic nervous system balance.',
      priority_level: 'High'
    });
  } else {
    suggestions.push({
      category: 'Energy Management',
      suggestion_title: 'Deep Work Flow State Capitalization',
      actionable_advice: 'Your cognitive reserve is strong. Eliminate secondary browser tabs and protect the next 50-minute interval for single-threaded deep problem solving.',
      priority_level: 'Low'
    });
  }

  // 3. Task Optimization
  if (taskResp.includes('behind') || taskResp.includes('no') || taskResp.includes('stuck') || taskResp.includes('fail')) {
    suggestions.push({
      category: 'Task Optimization',
      suggestion_title: 'Micro-Chunking & Friction Reduction',
      actionable_advice: `Deconstruct "${taskTitle}" into three bite-sized 15-minute sub-tasks. Lower the barrier to starting by tackling the simplest code commit or outline paragraph first.`,
      priority_level: 'High'
    });
  } else {
    suggestions.push({
      category: 'Task Optimization',
      suggestion_title: 'Milestone Archival & Asynchronous Handover',
      actionable_advice: 'Record completed sub-goals in your commit log or study notebook now to eliminate open cognitive loops and attention residue.',
      priority_level: 'Medium'
    });
  }

  // 4. Physical Well-being
  suggestions.push({
    category: 'Physical Well-being',
    suggestion_title: 'Postural Reset & 20-20-20 Ocular De-convergence',
    actionable_advice: 'Stand up and perform 5 thoracic rotations, chin tucks, and gaze at an object 20+ feet away for 20 seconds to release tension in suboccipital and ciliary muscles.',
    priority_level: fatigueScore >= 6 ? 'High' : 'Medium'
  });

  const wellnessSummary = mode === 'EVALUATE_RESPONSE'
    ? `User evaluated at ${currentTime}. Operational state shows cognitive fatigue at ${fatigueScore}/10. Priority interventions: ergonomic posture reset, targeted hydration, and micro-chunking scheduled tasks to preserve executive stamina.`
    : `Time-triggered check-in initiated at ${currentTime} analyzing schedule load and current task "${taskTitle}". Formulated 5 multidimensional wellness questions to evaluate immediate operational readiness.`;

  return {
    current_time_evaluated: currentTime,
    check_in_triggered: true,
    trigger_reason: triggerReason,
    check_in_questions: defaultQuestions,
    personalized_suggestions: suggestions,
    wellness_summary: wellnessSummary,
  };
}

